function Rarity.getByName(name)
	for _, tier in ipairs(Rarity.Tiers) do
		if tier.Name == name then
			return tier
		end
	end
	return nil
end

function Rarity.totalWeight(unlockedPower)
	local total = 0
	for _, tier in ipairs(Rarity.Tiers) do
		if unlockedPower >= tier.UnlockAt then
			total += tier.Weight
		end
	end
	return total
end

return Rarity
